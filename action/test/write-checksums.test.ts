import { spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtemp, readFile, rm, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { afterEach, beforeEach, describe, expect, it } from "vitest";
import { TARGETS as SCRIPT_TARGETS, writeChecksums } from "../../scripts/write-checksums.mjs";
import { TARGETS } from "../src/platform.js";

const SCRIPT = fileURLToPath(new URL("../../scripts/write-checksums.mjs", import.meta.url));

let dir: string;
let out: string;

beforeEach(async () => {
  dir = await mkdtemp(join(tmpdir(), "hoard-checksums-"));
  out = join(dir, "out", "checksums.generated.ts");
});

afterEach(async () => {
  await rm(dir, { recursive: true, force: true });
});

async function fakeAssets(targets: readonly string[]): Promise<Record<string, string>> {
  const sums: Record<string, string> = {};
  for (const t of targets) {
    const body = `fake archive for ${t}`;
    await writeFile(join(dir, `hoard-${t}.tar.gz`), body);
    sums[t] = createHash("sha256").update(body).digest("hex");
  }
  return sums;
}

describe("writeChecksums", () => {
  it("uses the same target list as platform.ts", () => {
    expect([...SCRIPT_TARGETS]).toEqual([...TARGETS]);
  });

  it("writes VERSION and one SHA-256 per target, in target order", async () => {
    const sums = await fakeAssets(TARGETS);
    await writeChecksums(dir, "1.2.3", out);
    const text = await readFile(out, "utf8");

    expect(text).toContain("generated by scripts/write-checksums.mjs — do not edit");
    expect(text).toContain('import type { Target } from "./platform.js";');
    expect(text).toContain('export const VERSION = "1.2.3";');
    expect(text).toContain("export const CHECKSUMS: Partial<Record<Target, string>> = {");
    const entries = [...text.matchAll(/"([a-z0-9_-]+)": "([0-9a-f]{64})",/g)];
    expect(entries.map((m) => m[1])).toEqual([...TARGETS]);
    for (const [, target, sum] of entries) expect(sum).toBe(sums[target]);
  });

  it("accepts a pre-release version", async () => {
    await fakeAssets(TARGETS);
    await writeChecksums(dir, "0.0.0-test", out);
    expect(await readFile(out, "utf8")).toContain('export const VERSION = "0.0.0-test";');
  });

  it("names the first missing target", async () => {
    await fakeAssets(TARGETS.filter((t) => t !== "aarch64-apple-darwin"));
    await expect(writeChecksums(dir, "1.2.3", out)).rejects.toThrow(
      "missing target aarch64-apple-darwin",
    );
  });

  it("rejects an unexpected extra asset", async () => {
    await fakeAssets([...TARGETS, "riscv64gc-unknown-linux-gnu"]);
    await expect(writeChecksums(dir, "1.2.3", out)).rejects.toThrow(
      "unexpected asset hoard-riscv64gc-unknown-linux-gnu.tar.gz",
    );
  });

  it.each(["v1.2.3", "1.2", "1.2.3-", "latest", ""])("rejects version %j", async (version) => {
    await fakeAssets(TARGETS);
    await expect(writeChecksums(dir, version, out)).rejects.toThrow("invalid version");
  });
});

describe("write-checksums CLI", () => {
  it("writes the file and exits 0 when all five assets are present", async () => {
    await fakeAssets(TARGETS);
    const r = spawnSync(process.execPath, [SCRIPT, dir, "1.2.3", out], { encoding: "utf8" });
    expect(r.status).toBe(0);
    expect(await readFile(out, "utf8")).toContain('export const VERSION = "1.2.3";');
  });

  it("exits non-zero with the error on stderr when a target is missing", async () => {
    await fakeAssets(TARGETS.slice(1));
    const r = spawnSync(process.execPath, [SCRIPT, dir, "1.2.3", out], { encoding: "utf8" });
    expect(r.status).not.toBe(0);
    expect(r.stderr).toContain("missing target x86_64-unknown-linux-musl");
  });
});
