#!/usr/bin/env node
// Writes action/src/checksums.generated.ts from the release assets: the SHA-256 of each
// hoard-<target>.tar.gz, so the action only ever runs a binary it can verify (spec §10).
//
// Usage: node scripts/write-checksums.mjs <assetDir> <version> [outFile]

import { createHash } from "node:crypto";
import { createReadStream } from "node:fs";
import { mkdir, readdir, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { pipeline } from "node:stream/promises";
import { fileURLToPath } from "node:url";

// Same list, same order as TARGETS in action/src/platform.ts (a test asserts they are equal).
export const TARGETS = [
  "x86_64-unknown-linux-musl",
  "aarch64-unknown-linux-musl",
  "x86_64-apple-darwin",
  "aarch64-apple-darwin",
  "x86_64-pc-windows-msvc",
];

const VERSION_RE = /^\d+\.\d+\.\d+(-[0-9A-Za-z.-]+)?$/;
const ASSET_RE = /^hoard-.+\.tar\.gz$/;

export const DEFAULT_OUT = fileURLToPath(
  new URL("../action/src/checksums.generated.ts", import.meta.url),
);

async function sha256(file) {
  const hash = createHash("sha256");
  await pipeline(createReadStream(file), hash);
  return hash.digest("hex");
}

export async function writeChecksums(assetDir, version, outFile = DEFAULT_OUT) {
  if (typeof version !== "string" || !VERSION_RE.test(version)) {
    throw new Error(`invalid version ${JSON.stringify(version)}: expected X.Y.Z or X.Y.Z-pre`);
  }

  const assets = new Set((await readdir(assetDir)).filter((name) => ASSET_RE.test(name)));
  for (const target of TARGETS) {
    if (!assets.has(`hoard-${target}.tar.gz`)) throw new Error(`missing target ${target}`);
  }
  const expected = new Set(TARGETS.map((t) => `hoard-${t}.tar.gz`));
  const extra = [...assets].filter((name) => !expected.has(name)).sort();
  if (extra.length > 0) throw new Error(`unexpected asset ${extra.join(", ")}`);

  const lines = [];
  for (const target of TARGETS) {
    lines.push(`  "${target}": "${await sha256(join(assetDir, `hoard-${target}.tar.gz`))}",`);
  }

  const text = [
    "// generated by scripts/write-checksums.mjs — do not edit",
    'import type { Target } from "./platform.js";',
    "",
    `export const VERSION = "${version}";`,
    "",
    "export const CHECKSUMS: Partial<Record<Target, string>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");

  await mkdir(dirname(outFile), { recursive: true });
  await writeFile(outFile, text);
  return outFile;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [assetDir, version, outFile] = process.argv.slice(2);
  if (!assetDir || !version) {
    console.error("usage: node scripts/write-checksums.mjs <assetDir> <version> [outFile]");
    process.exit(2);
  }
  writeChecksums(assetDir, version, outFile ?? DEFAULT_OUT).then(
    (file) => console.log(`wrote ${file}`),
    (err) => {
      console.error(`write-checksums: ${err.message}`);
      process.exit(1);
    },
  );
}
