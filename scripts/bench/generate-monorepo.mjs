#!/usr/bin/env node
// Generates a pnpm + Turborepo workspace of N independent packages for the rate-limit benchmark
// (.github/workflows/bench.yml). Usage: node generate-monorepo.mjs <outDir> <packages>
//
// Every package has a portable `build` (a node script, no shell) that writes dist/out.txt:
// its name plus a fixed, run-independent payload of about 2 KB (about 1 KB once
// zstd-compressed). The inputs are the same on every job, so task hashes are identical
// between the cold and warm jobs. There are no inter-package dependencies, so turbo can
// start every upload at once.
//
// No lockfile is generated: turbo is the only dependency, and the workflow installs with
// `pnpm install --no-frozen-lockfile`. A lockfile would pin one resolution but its content
// would not change any task hash we measure, and it would have to be regenerated by a
// network-bound pnpm run to be correct.
import { mkdirSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const MIN_PACKAGES = 1;
export const MAX_PACKAGES = 5000;
const TURBO_VERSION = "2.11.8";
const PNPM_VERSION = "10.28.0";

const json = (v) => `${JSON.stringify(v, null, 2)}\n`;

const BUILD_SCRIPT = `// Writes dist/out.txt: the package name plus a deterministic ~2 KB payload.
import { createHash } from "node:crypto";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
const { name } = JSON.parse(readFileSync(new URL("./package.json", import.meta.url), "utf8"));
// A sha256 chain seeded by the name: high-entropy hex, so the zstd
// artifact stays near 1 KB.
const lines = [name];
let h = name;
for (let i = 0; i < 24; i++) {
  h = createHash("sha256").update(h).digest("hex");
  lines.push(h + h.slice(0, 16));
}
mkdirSync("dist", { recursive: true });
writeFileSync("dist/out.txt", lines.join("\\n") + "\\n");
`;

export function generateMonorepo(outDir, packages) {
  if (!Number.isInteger(packages) || packages < MIN_PACKAGES || packages > MAX_PACKAGES) {
    throw new RangeError(`packages must be an integer from ${MIN_PACKAGES} to ${MAX_PACKAGES}, got ${packages}`);
  }
  const root = resolve(outDir);
  mkdirSync(join(root, "packages"), { recursive: true });
  writeFileSync(
    join(root, "package.json"),
    json({
      name: "hoard-bench",
      private: true,
      packageManager: `pnpm@${PNPM_VERSION}`,
      devDependencies: { turbo: TURBO_VERSION },
    }),
  );
  writeFileSync(join(root, "pnpm-workspace.yaml"), 'packages:\n  - "packages/*"\n');
  writeFileSync(
    join(root, "turbo.json"),
    json({
      $schema: "https://turborepo.com/schema.json",
      tasks: { build: { outputs: ["dist/**"] } },
    }),
  );
  writeFileSync(join(root, ".gitignore"), "node_modules\ndist\n.turbo\n");
  const width = Math.max(4, String(packages).length);
  for (let i = 1; i <= packages; i++) {
    const id = `pkg-${String(i).padStart(width, "0")}`;
    const dir = join(root, "packages", id);
    mkdirSync(dir, { recursive: true });
    writeFileSync(
      join(dir, "package.json"),
      json({
        name: `@bench/${id}`,
        version: "1.0.0",
        private: true,
        type: "module",
        scripts: { build: "node build.mjs" },
      }),
    );
    writeFileSync(join(dir, "build.mjs"), BUILD_SCRIPT);
  }
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const [outDir, n, ...rest] = process.argv.slice(2);
  const count = /^\d+$/.test(n ?? "") ? Number(n) : Number.NaN;
  if (!outDir || rest.length > 0 || !Number.isInteger(count)) {
    console.error("usage: generate-monorepo.mjs <outDir> <packages (1..5000)>");
    process.exit(2);
  }
  try {
    generateMonorepo(outDir, count);
  } catch (e) {
    console.error(e.message);
    process.exit(2);
  }
  console.log(`generated ${count} packages in ${resolve(outDir)}`);
}
